<#
.SYNOPSIS
    Step 3 - build the pjproject static library for x64.

.DESCRIPTION
    Builds upstream pjproject 2.14.1 (the archive in third_party\src) as
    "Debug-Static|x64" and "Release-Static|x64" and installs the result into
    third_party\lib\.

    Two upstream quirks have to be handled:

    1. pjmedia-codec/opus.c carries a GNU style pragma
           #pragma comment(lib, "libopus.a")
       It is baked into the object file and travels with the static library,
       so every consumer ends up asking the MSVC linker for "libopus.a".
       Upstream only ever built opus with MinGW, where that name is correct.

    2. The OpenSSL headers are needed by more than pjlib: pjsip_core needs
       openssl/sha.h (HTTP digest authentication) and pjmedia needs
       openssl/rand.h (DTLS-SRTP). The include path is therefore added to
       every project through a local props file.

    The toolset has to be overridden: upstream's build/vs props hardcode v140,
    which no longer ships. A global /p:BuildToolset overrides the props file.

.EXAMPLE
    .\03-pjproject.ps1 -Platform x64
#>
[CmdletBinding()]
param(
    [ValidateSet('x64', 'Win32')][string]$Platform = 'x64',
    [string]$RepoRoot = '',
    [switch]$Rebuild
)

. (Join-Path $PSScriptRoot '_common.ps1')

if (-not $RepoRoot) { $RepoRoot = Get-RepoRoot }
$work = Get-WorkDir $RepoRoot
$tp = Join-Path $RepoRoot 'third_party'
$tree = Join-Path $work 'pjproject-2.14.1'

if (-not (Test-Path (Join-Path $tree 'pjsip-apps\build\libpjproject.vcxproj'))) {
    throw "pjproject source not found in $tree - run 01-prepare.ps1 first"
}

Write-Step "patching pjproject tree"

# --- upstream opus.c pragma ---------------------------------------------
$opusC = Join-Path $tree 'pjmedia\src\pjmedia-codec\opus.c'
$text = Get-Content $opusC -Raw
if ($text -match 'pragma comment\(lib,\s*"libopus\.a"\)') {
    $text = $text -replace 'pragma comment\(lib,\s*"libopus\.a"\)', 'pragma comment(lib, "opus.lib")'
    Set-Content -Path $opusC -Value $text -Encoding utf8 -NoNewline
    Write-Ok 'opus.c            : libopus.a -> opus.lib'
} else {
    Write-Ok 'opus.c            : pragma already correct'
}

# --- local props ---------------------------------------------------------
$opusInclude = Join-Path $tp 'opus\include'
$sslInclude = Join-Path $tp 'openssl\Win32\include'
$propsPath = Join-Path $tree 'build\vs\pjproject-vs14-local-deps.props'
$props = @"
<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by build\steps\03-pjproject.ps1 - do not edit by hand. -->
<Project DefaultTargets="Build" xmlns="http://schemas.microsoft.com/developer/msbuild/2003">
  <PropertyGroup>
    <LocalOpusInclude Condition="'`$(LocalOpusInclude)'==''">$opusInclude</LocalOpusInclude>
    <LocalOpenSslInclude Condition="'`$(LocalOpenSslInclude)'==''">$sslInclude</LocalOpenSslInclude>
  </PropertyGroup>
  <ItemDefinitionGroup>
    <ClCompile>
      <AdditionalIncludeDirectories>`$(LocalOpenSslInclude);%(AdditionalIncludeDirectories)</AdditionalIncludeDirectories>
    </ClCompile>
  </ItemDefinitionGroup>
  <ItemDefinitionGroup Condition="'`$(ProjectName)'=='pjmedia_codec'">
    <ClCompile>
      <AdditionalIncludeDirectories>`$(LocalOpusInclude);%(AdditionalIncludeDirectories)</AdditionalIncludeDirectories>
    </ClCompile>
  </ItemDefinitionGroup>
</Project>
"@
Set-Content -Path $propsPath -Value $props -Encoding utf8
Write-Ok "local props       : build\vs\pjproject-vs14-local-deps.props"

# --- import the props into every project --------------------------------
$pattern = '(?m)^([ \t]*)<Import\s+Project="([^"]*pjproject-vs14-common-config\.props)"\s*/>'
$patched = 0
foreach ($p in Get-ChildItem $tree -Recurse -File -Filter '*.vcxproj') {
    $t = Get-Content $p.FullName -Raw
    if ($t -match 'pjproject-vs14-local-deps\.props') { continue }
    $new = [regex]::Replace($t, $pattern, {
        param($m)
        $indent = $m.Groups[1].Value
        $path = $m.Groups[2].Value -replace 'pjproject-vs14-common-config\.props', 'pjproject-vs14-local-deps.props'
        "$($m.Value)`r`n$indent<Import Project=`"$path`" />"
    })
    if ($new -ne $t) {
        Set-Content -Path $p.FullName -Value $new -Encoding utf8 -NoNewline
        $patched++
    }
}
Write-Ok "projects patched  : $patched"

# --- build ---------------------------------------------------------------
Write-Step "building pjproject ($Platform)"

$proj = Join-Path $tree 'pjsip-apps\build\libpjproject.vcxproj'
$toolset = Get-PlatformToolset
$target = if ($Rebuild) { 'Rebuild' } else { 'Build' }

foreach ($cfg in @('Debug-Static', 'Release-Static')) {
    Write-Host "   $cfg ..."
    Invoke-MsBuild $proj @("/t:$target", "/p:Configuration=$cfg", "/p:Platform=$Platform",
        "/p:BuildToolset=$toolset", '/m', '/v:m', '/nologo') "pjproject $cfg" | Out-Null
}

# --- install -------------------------------------------------------------
Write-Step 'installing pjproject libraries'
$dest = Join-Path $tp 'lib'
New-Item -ItemType Directory -Force -Path $dest | Out-Null
foreach ($f in Get-ChildItem (Join-Path $tree 'lib') -Filter "libpjproject-*-$Platform-vc14-*.lib") {
    Copy-Item $f.FullName (Join-Path $dest $f.Name) -Force
    Write-Ok ("third_party\lib\{0}  ({1:N0} bytes)" -f $f.Name, $f.Length)
}

Write-Host ''
Write-Host 'RESULT: pjproject ready.' -ForegroundColor Green
